import json,os
keys=[];en=[]
for l in open('i18n_en.txt',encoding='utf8'):
  l=l.rstrip('\n')
  if not l:continue
  k,v=l.split('|',1);keys.append(k);en.append(v)
langs=['en','th','zh','hi','es','ar','fr','pt','ru','ja','de','id','ko','tr','vi','it','pl','nl','fil','ms','bn']
raw={'en':en}
for L in langs[1:]:
  p='tr/%s.txt'%L
  if os.path.exists(p):
    vals=[x.rstrip('\n') for x in open(p,encoding='utf8') if x.strip()]
    if len(vals)!=len(keys):print('COUNT MISMATCH',L,len(vals),len(keys))
    raw[L]=vals
names={"en":"English","th":"ไทย","zh":"中文","hi":"हिन्दी","es":"Español","ar":"العربية","fr":"Français","pt":"Português","ru":"Русский","ja":"日本語","de":"Deutsch","id":"Bahasa Indonesia","ko":"한국어","tr":"Türkçe","vi":"Tiếng Việt","it":"Italiano","pl":"Polski","nl":"Nederlands","fil":"Filipino","ms":"Bahasa Melayu","bn":"বাংলা"}
js='// Rocket Star Blitz — translations (auto-detected from device language; ?lang=xx override). Title stays English. GENERATED by build_i18n.py\n'
js+='const I18N_KEYS='+json.dumps(keys)+';\nconst I18N_RAW='+json.dumps(raw,ensure_ascii=False,indent=0)+';\n'
js+='const LANG_NAMES='+json.dumps({k:names[k] for k in langs},ensure_ascii=False)+';\n'
js+='''const I18N={};for(const l in I18N_RAW){I18N[l]={};I18N_KEYS.forEach((k,i)=>I18N[l][k]=I18N_RAW[l][i]);}
function detectLang(){const q=new URLSearchParams(location.search).get('lang');let saved=null;try{saved=localStorage.getItem('rsb_lang');}catch(e){}
  const cands=[q,saved,...(navigator.languages||[]),navigator.language].filter(Boolean);
  for(const c of cands){const l=c.toLowerCase();if(l.startsWith('tl'))return 'fil';const b=l.split('-')[0];if(I18N[b])return b;}
  return 'en';}
let LANG=detectLang();
function T(k){return (I18N[LANG]&&I18N[LANG][k])||I18N.en[k]||k;}
'''
open('i18n.js','w',encoding='utf8').write(js);print('langs',list(raw))
